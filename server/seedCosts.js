async function seedRepairCosts() {
  try {
    const existingCount = await get('SELECT COUNT(*) as count FROM repair_costs');
    if (existingCount && existingCount.count > 0) {
      console.log(`Repair costs already populated (${existingCount.count} entries).`);
      return;
    }

    console.log('Seeding Repair Cost Intelligence database...');
    for (const item of REPAIR_COST_ENTRIES) {
      await run(`
        INSERT INTO repair_costs (
          id, category_slug, brand_slug, brand_name, model_name, component_name, city,
          official_price, official_labour, official_tax_inclusive, official_part_quality, official_source_url, official_warranty,
          auth_price, auth_labour, auth_tax_inclusive, auth_part_quality, auth_source_url, auth_warranty,
          local_min_price, local_max_price, local_labour, local_part_quality, local_warranty,
          repairsathi_estimate, last_verified_date, data_confidence
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
      `, [
        randomUUID(),
        item.category_slug,
        item.brand_slug,
        item.brand_name,
        item.model_name,
        item.component_name,
        item.city,
        item.official_price,
        item.official_labour,
        item.official_tax_inclusive,
        item.official_part_quality,
        item.official_source_url,
        item.official_warranty,
        item.auth_price,
        item.auth_labour,
        item.auth_tax_inclusive,
        item.auth_part_quality,
        item.auth_source_url,
        item.auth_warranty,
        item.local_min_price,
        item.local_max_price,
        item.local_labour,
        item.local_part_quality,
        item.local_warranty,
        item.repairsathi_estimate,
        item.last_verified_date,
        item.data_confidence
      ]);
    }
    console.log(`Successfully seeded ${REPAIR_COST_ENTRIES.length} repair cost intelligence entries.`);
  } catch (err) {
    console.error('Error seeding repair costs:', err);
  }
}

